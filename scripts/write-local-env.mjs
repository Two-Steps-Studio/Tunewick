// Writes apps/web/.env.local from the running local Supabase (pnpm db:start first).
// Only public values (URL + publishable key) are written; .env.local is git-ignored.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { LOCAL_MEDIA } from "./media-start.mjs";

const status = execSync("pnpm exec supabase status -o env", { encoding: "utf8" });
const env = Object.fromEntries(
  status
    .split(/\r?\n/)
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2]]),
);

if (!env.API_URL || !env.PUBLISHABLE_KEY) {
  console.error("Local Supabase is not running. Run `pnpm db:start` first.");
  process.exit(1);
}

// Local S3 (pnpm media:start) — server-only settings, included only while it runs.
let mediaRunning = false;
try {
  mediaRunning = execSync("docker ps --filter name=tunewick-media --format {{.Names}}", {
    encoding: "utf8",
  }).includes("tunewick-media");
} catch {}
const media = mediaRunning
  ? [
      "# Local S3 standing in for R2 (docker/media). Server-only.",
      `MEDIA_S3_ENDPOINT=${LOCAL_MEDIA.endpoint}`,
      `MEDIA_S3_REGION=${LOCAL_MEDIA.region}`,
      `MEDIA_S3_ACCESS_KEY_ID=${LOCAL_MEDIA.accessKeyId}`,
      `MEDIA_S3_SECRET_ACCESS_KEY=${LOCAL_MEDIA.secretAccessKey}`,
      `MEDIA_INGEST_BUCKET=${LOCAL_MEDIA.ingestBucket}`,
      `MEDIA_BUCKET=${LOCAL_MEDIA.mediaBucket}`,
    ]
  : ["# Audio upload disabled: run `pnpm media:start` for local S3, then `pnpm db:env`."];

writeFileSync(
  "apps/web/.env.local",
  [
    "# Generated by scripts/write-local-env.mjs for local development. Do not commit.",
    `NEXT_PUBLIC_SUPABASE_URL=${env.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${env.PUBLISHABLE_KEY}`,
    ...media,
    "",
  ].join("\n"),
);
console.log("Wrote apps/web/.env.local");
